    public function testAllAlwaysAnswers()
    {
        // Contesta todas las preguntas con `always`.
        while ($questionId = $this->queryNextQuestion($this->stage->id, $this->child->id)->json('data.nextQuestion.id')) {
            $this->mutation(
                'answer',
                [
                    'input' => [
                        'childId' => $this->child->id,
                        'questionId' => $questionId,
                        'answerOptionId' => 1,
                    ],
                ],
                [
                    'id',
                ]
            );
        }
        // El niño debe tener un resultado por cada área.
        $areas = Area::all();
        $results = $this->child->results()->where('stage_id', $this->stage->id)->get();
        $this->assertEquals($areas->count(), $results->count());
        foreach ($results as $result) {
            $this
                ->query(
                    'result',
                    ['id' => $result->id],
                    [
                        'id',
                        'percentage',
                        'slug',
                        'info' => [
                            'data' => [
                                'display',
                            ],
                        ],
                        'games' => [
                            'data' => [
                                'title',
                            ],
                        ],
                    ]
                )
                ->item(function (TestItem $result) {
                    $result->assertAttribute(1, $result->percentage);
                });
        }

        $this
            ->query(
                'stages',
                [],
                [
                    'data' => [
                        'id',
                        "unlocked (childId: {$this->child->id})",
                    ]
                ]
            )
            ->collection(function (TestCollection $stages) {
                $this->assertTrue(Arr::get($stages->collection, '0.unlocked'));
                $this->assertTrue(Arr::get($stages->collection, '1.unlocked'));
                $this->assertFalse(Arr::get($stages->collection, '2.unlocked'));
            });
    }


    private function calculate($possibilities)
    {
        foreach (Area::all() as $area) {
            $possibilitiesCopy = $possibilities;

            $questions = $area->questions()
                ->where('stage_id', '=', $this->stage->id)
                ->where('ageRange_id', '=', $this->child->ageRange_id)
                ->get();

            foreach ($questions as $question) {
                $answer = AnswerOption::whereSlug($this->getNextAnswer($possibilitiesCopy))->first();
                $this->mutation(
                    'answer',
                    [
                        'input' => [
                            'childId' => $this->child->id,
                            'questionId' => $question->id,
                            'answerOptionId' => $answer->id,
                        ],
                    ],
                    [
                        'id',
                    ]
                );
            }
        }

        $areas = Area::all();
        $results = $this->child->results()->where('stage_id', $this->stage->id)->get();
        $this->assertEquals($areas->count(), $results->count());

        $percentageResults = collect();
        foreach ($results as $result) {
            $this
                ->query(
                    'result',
                    ['id' => $result->id],
                    [
                        'id',
                        'percentage',
                        'slug',
                        'info' => [
                            'data' => [
                                'display',
                            ],
                        ],
                        'games' => [
                            'data' => [
                                'title',
                            ],
                        ],
                    ]
                )
                ->item(function (TestItem $result) use ($percentageResults) {
                    $percentageResults->push($result->percentage);
                    //                    $result->assertAttribute(0, $result->percentage);
                });
        }
        return $percentageResults;
    }

    /**
     * Determina cual debe ser la siguiente respuesta, teniendo en cuenta
     * cuantas se deben responder.
     * Por ejemplo, teniendo:
     * ```
     * $posibilities = ['always' => 6, 'sometimes' => 3, 'never' => 3];
     * ```
     * Devolverá 6 veces `always`, 3 `sometimes` y 3 `never`.
     *
     * @param array $possibilities
     *
     * @return string
     */
    private function getNextAnswer(array &$possibilities)
    {
        if (Arr::get($possibilities, 'always') > 0) {
            Arr::set($possibilities, 'always', Arr::get($possibilities, 'always') - 1);
            return 'always';
        } elseif (Arr::get($possibilities, 'sometimes') > 0) {
            Arr::set($possibilities, 'sometimes', Arr::get($possibilities, 'sometimes') - 1);
            return 'sometimes';
        } elseif (Arr::get($possibilities, 'never') > 0) {
            Arr::set($possibilities, 'never', Arr::get($possibilities, 'never') - 1);
            return 'never';
        }
    }

